export function RavaelPixelArt() {
  const stageRef = useRef<HTMLDivElement>(null);
  const [scale, setScale] = useState(1);

  useEffect(() => {
    const el = stageRef.current;
    if (!el) return;

    const update = () => {
      const w = el.clientWidth;
      if (w > 0) {
        setScale(Math.min(1, w / 880));
      }
    };

    update();
    const ro = typeof ResizeObserver !== 'undefined' ? new ResizeObserver(update) : null;
    ro?.observe(el);
    window.addEventListener('resize', update);
    return () => {
      ro?.disconnect();
      window.removeEventListener('resize', update);
    };
  }, []);

  const labelTop = Math.round(224 * scale);
  const stageHeight = labelTop + 20;

  return (
    <div
      ref={stageRef}
      role="img"
      aria-label="RAVAEL"
      className="relative w-full overflow-hidden select-none"
      style={{ height: stageHeight }}
    >
      <div
        aria-hidden="true"
        style={{
          position: 'absolute',
          left: '50%',
          top: 0,
          width: 880,
          height: 260,
          transformOrigin: 'top left',
          transform: `translateX(${-440 * scale}px) scale(${scale})`,
        }}
      >
        {PIXELS.map(([left, top, dx, dy, delay], idx) => (
          <i
            key={`p-${idx}`}
            className="bp-px-cell"
            style={
              {
                left: `${left}px`,
                top: `${top}px`,
                '--x': `${dx}px`,
                '--y': `${dy}px`,
                '--d': `${delay}s`,
              } as React.CSSProperties
            }
          />
        ))}
        {STRAYS.map(([left, top, delay], idx) => (
          <b
            key={`s-${idx}`}
            className="bp-px-stray"
            style={
              {
                left: `${left}px`,
                top: `${top}px`,
                '--d': `${delay}s`,
              } as React.CSSProperties
            }
          />
        ))}
      </div>

      <span
        className="bp-px-label-raw absolute left-4 md:left-6 font-mono text-[11px] sm:text-[12px] text-[#555555] dark:text-[#a3a3a3] pointer-events-none"
        style={{ top: labelTop }}
      >
        raw_data.csv
      </span>
      <span
        className="bp-px-label-clean absolute left-4 md:left-6 font-mono text-[11px] sm:text-[12px] text-[#555555] dark:text-[#a3a3a3] pointer-events-none"
        style={{ top: labelTop }}
      >
        clean_data.csv
      </span>
    </div>
  );
}
